// Command gen writes the base exports of a LumberJack C archive: one //export wrapper per base
// function in lumberjack.h, each a thin call into ffi/abi (docs/extension-api.md §6, owner decision
// Q7(a)). The generic archive (./ffi) is these wrappers and nothing else; a product archive is these
// wrappers, its own exports, and an init that calls abi.Register. The wrappers live in each archive's
// main package because cgo's generated header lists only the main package's exports, and
// `make header-check` compares that header with the specification.
//
//	go run github.com/NeoTecDigital/LumberJack/ffi/gen -include <dir holding lumberjack.h> > base_exports.go
package main

import (
	"flag"
	"fmt"
	"go/format"
	"io"
	"os"
	"strings"
)

// export is one base function: its C name, its parameters as cgo sees them, and the abi call.
type export struct {
	name, params, result, call string
}

// dataParams is the parameter list every data export shares.
const dataParams = "h C.lj_handle_t, req C.lj_cstr, reqLen C.int64_t, out *C.char, outCap C.int64_t, outLen *C.int64_t"

// dataArgs is that list as abi takes it.
const dataArgs = "uint64(h), unsafe.Pointer(req), int64(reqLen), unsafe.Pointer(out), int64(outCap), unsafe.Pointer(outLen)"

func dataExport(name, function string) export {
	return export{name, dataParams, "C.lj_status_t", "C.lj_status_t(abi." + function + "(" + dataArgs + "))"}
}

// baseExports are the nineteen, in the order lumberjack.h declares them.
var baseExports = []export{
	{"ic_lj_abi_version", "", "C.uint32_t", "C.uint32_t(abi.AbiVersion())"},
	{"ic_lj_open", "req C.lj_cstr, reqLen C.int64_t, outHandle *C.lj_handle_t", "C.lj_status_t",
		"C.lj_status_t(abi.Open(unsafe.Pointer(req), int64(reqLen), unsafe.Pointer(outHandle)))"},
	{"ic_lj_adopt", "req C.lj_cstr, reqLen C.int64_t", "C.lj_status_t", "C.lj_status_t(abi.Adopt(unsafe.Pointer(req), int64(reqLen)))"},
	{"ic_lj_close", "h C.lj_handle_t", "C.lj_status_t", "C.lj_status_t(abi.Close(uint64(h)))"},
	dataExport("ic_lj_node_create", "NodeCreate"),
	dataExport("ic_lj_event_plan", "EventPlan"),
	dataExport("ic_lj_event_start", "EventStart"),
	dataExport("ic_lj_events_publish", "EventsPublish"),
	dataExport("ic_lj_event_append", "EventAppend"),
	dataExport("ic_lj_event_end", "EventEnd"),
	dataExport("ic_lj_event_entries", "EventEntries"),
	dataExport("ic_lj_query", "Query"),
	dataExport("ic_lj_aggregate", "Aggregate"),
	dataExport("ic_lj_forest", "Forest"),
	dataExport("ic_lj_stream_poll", "StreamPoll"),
	{"ic_lj_echo", "in C.lj_cstr, inLen C.int64_t, out *C.char, outCap C.int64_t, outLen *C.int64_t", "C.lj_status_t",
		"C.lj_status_t(abi.Echo(unsafe.Pointer(in), int64(inLen), unsafe.Pointer(out), int64(outCap), unsafe.Pointer(outLen)))"},
	{"ic_lj_application_configure", "h C.lj_handle_t, req C.lj_cstr, reqLen C.int64_t", "C.lj_status_t",
		"C.lj_status_t(abi.ApplicationConfigure(uint64(h), unsafe.Pointer(req), int64(reqLen)))"},
	{"ic_lj_application_call", "h C.lj_handle_t, req C.lj_cstr, reqLen C.int64_t, out **C.char, outLen *C.int64_t", "C.lj_status_t",
		"C.lj_status_t(abi.ApplicationCall(uint64(h), unsafe.Pointer(req), int64(reqLen), unsafe.Pointer(out), unsafe.Pointer(outLen)))"},
	{"ic_lj_application_free", "out *C.char", "", "abi.ApplicationFree(unsafe.Pointer(out))"},
}

// Write writes the wrappers for package pkg, with lumberjack.h found in include.
func Write(w io.Writer, pkg, include string) error {
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by go run github.com/NeoTecDigital/LumberJack/ffi/gen; DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package %s\n\n/*\n#cgo CFLAGS: -I${SRCDIR}%s\n#include \"lumberjack.h\"\n*/\nimport \"C\"\n\n", pkg, include)
	b.WriteString("import (\n\t\"unsafe\"\n\n\t\"github.com/NeoTecDigital/LumberJack/ffi/abi\"\n)\n\n")
	b.WriteString("// The base exports: each is its abi function, on the archive's own C types.\n")
	for _, e := range baseExports {
		fmt.Fprintf(&b, "\n//export %s\nfunc %s(%s)", e.name, e.name, e.params)
		if e.result != "" {
			fmt.Fprintf(&b, " %s { return %s }\n", e.result, e.call)
		} else {
			fmt.Fprintf(&b, " { %s }\n", e.call)
		}
	}
	formatted, err := format.Source([]byte(b.String()))
	if err != nil {
		return err
	}
	_, err = w.Write(formatted)
	return err
}

func main() {
	pkg := flag.String("package", "main", "the package the wrappers belong to")
	include := flag.String("include", "", "lumberjack.h's directory, relative to the generated file's (e.g. /.. ); empty is the same directory")
	flag.Parse()
	if err := Write(os.Stdout, *pkg, *include); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
